class UserMemory:

    def __init__(self):

        self.profile = {}

    # =========================================================
    # SET
    # =========================================================

    def set(self, key, value):

        self.profile[key] = value

    # =========================================================
    # GET
    # =========================================================

    def get(self, key):

        return self.profile.get(key)

    # =========================================================
    # HAS
    # =========================================================

    def has(self, key):

        return key in self.profile

    # =========================================================
    # ALL
    # =========================================================

    def all(self):

        return dict(self.profile)